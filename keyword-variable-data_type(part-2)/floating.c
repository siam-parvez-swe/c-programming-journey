// write a programme that print floating, double and character data type
#include <stdio.h>
int main()
{
    // floating data type
    float num1= 1.2450;
    double num2 = 1.248783459834575384;
    char ch = 'S';
    printf("Floating number is %.2f \n", num1);
    printf("Floating number is %f \n", num1);
    printf("Double number is %lf \n", num2);
    printf("Character number is %c", ch);
    return 0;
}